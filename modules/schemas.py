from enum import Enum
from typing import List, Dict, Any, Optional
from datetime import datetime, timezone
from pydantic import BaseModel, Field

class ValidationStatus(str, Enum):
    VALIDATED = "VALIDATED"
    NEEDS_REVIEW = "NEEDS_REVIEW"
    REJECTED = "REJECTED"

class InputRecord(BaseModel):
    input_id: str
    source: str
    row_count: int
    column_count: int
    features: List[str]
    target: Optional[str] = None
    metadata: Dict[str, Any] = Field(default_factory=dict)
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

class PatternRecord(BaseModel):
    pattern_id: str
    input_id: str
    pattern_type: str
    features: List[str]
    metrics: Dict[str, Any] = Field(default_factory=dict)
    description: str
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

class HypothesisRecord(BaseModel):
    hypothesis_id: str
    iteration_no: int = 1
    hypothesis_type: str
    hypothesis: str
    features_involved: List[str] = Field(default_factory=list)
    evidence_from_data: str = ""
    proposed_experiment: str = ""
    fingerprint: Optional[str] = None
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def model_post_init(self, __context: Any) -> None:
        if self.fingerprint is None:
            sorted_feats = tuple(sorted(self.features_involved))
            self.fingerprint = f"{sorted_feats}-{self.hypothesis_type}"

class ValidationResultRecord(BaseModel):
    validation_id: str
    hypothesis_id: str
    iteration_no: int = 1
    hypothesis_type: Optional[str] = None
    status: ValidationStatus
    features_involved: List[str] = Field(default_factory=list)
    reconciled_evidence: Dict[str, Any] = Field(default_factory=dict)
    reasons: List[str] = Field(default_factory=list)
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

class ValidationReportRecord(BaseModel):
    report_id: str
    iteration_no: int = 1
    total: int
    validated_count: int
    needs_review_count: int
    rejected_count: int
    results: List[ValidationResultRecord] = Field(default_factory=list)
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

class ExperimentSpecRecord(BaseModel):
    experiment_id: str
    hypothesis_id: str
    iteration_no: int = 1
    experiment_type: str
    method: str
    model_type: str
    features: List[str]
    target: str
    comparison: Optional[List[List[str]]] = None
    parameters: Dict[str, Any] = Field(default_factory=dict)
    evaluation: Dict[str, Any] = Field(default_factory=dict)
    routing_notes: Optional[str] = None
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

class ExperimentResultRecord(BaseModel):
    result_id: str
    experiment_id: str
    hypothesis_id: str
    iteration_no: int = 1
    experiment_type: str
    method: str
    model_type: str
    features: List[str]
    target: str
    metrics: Dict[str, Any] = Field(default_factory=dict)
    details: Dict[str, Any] = Field(default_factory=dict)
    verdict: Optional[str] = None  # SUPPORTED, REFUTED, INCONCLUSIVE
    summary: str = ""
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class StandardExperimentResult(BaseModel):
    """
    Standard common outer result structure for Batch 4 Result Evaluation.
    """
    experiment_id: str
    hypothesis_id: str
    iteration_no: int = 1
    status: str = "completed"
    experiment_type: str
    configuration: Dict[str, Any] = Field(default_factory=dict)
    results: Dict[str, Any] = Field(default_factory=dict)
    statistical_validation: Dict[str, Any] = Field(default_factory=dict)
    evaluation: Dict[str, Any] = Field(default_factory=dict)
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class CrossExperimentComparisonRecord(BaseModel):
    """
    Aggregated cross-experiment baseline comparison matrix (Batch 4.5).
    """
    comparison_id: str
    iteration_no: int = 1
    individual_baselines: Dict[str, float] = Field(default_factory=dict)
    combination_scores: Dict[str, float] = Field(default_factory=dict)
    synergy_gains: Dict[str, float] = Field(default_factory=dict)
    ranking: List[Dict[str, Any]] = Field(default_factory=list)
    summary_findings: List[str] = Field(default_factory=list)
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class LLMInterpretationRecord(BaseModel):
    """
    Structured interpretation and findings reasoning generated by local LLM (Batch 5).
    """
    interpretation_id: str
    experiment_id: str
    hypothesis_id: str
    iteration_no: int = 1
    hypothesis_status: str  # supported_by_current_evidence, not_supported, inconclusive
    interpretation: str
    observations: List[str] = Field(default_factory=list)
    limitations: List[str] = Field(default_factory=list)
    next_hypothesis: str = ""
    proposed_experiment: Dict[str, Any] = Field(default_factory=dict)
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class RefinedHypothesisRecord(BaseModel):
    """
    Refined follow-up hypothesis formatted to feed into subsequent iterations (Iteration N+1).
    """
    hypothesis_id: str
    parent_hypothesis_id: str
    iteration_no: int
    hypothesis: str
    rationale: str = ""
    proposed_experiment: Dict[str, Any] = Field(default_factory=dict)
    features_involved: List[str] = Field(default_factory=list)
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


